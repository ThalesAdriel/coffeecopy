//! Interface languages. English is the native language of the app: the English text is
//! the lookup key, and every other language maps it to a translation.
//!
//! Terminology follows the official Windows / Microsoft localization:
//!   Clipboard history  ru «Журнал буфера обмена»  zh «剪贴板历史记录»  ja «クリップボードの履歴»
//!   Settings           ru «Параметры»             zh «设置»            ja «設定»
//!   Paste / Delete     ru «Вставить» / «Удалить»  zh «粘贴» / «删除»    ja «貼り付け» / «削除»
//!   Light theme / Accent color  ru «Светлая» / «Акцентный цвет»  zh «浅色» / «强调色»  ja «ライト» / «アクセント カラー»
//! (see support.microsoft.com "Using the clipboard", ru-ru / zh-cn / ja-jp).

pub const LANG_NAMES: [&str; 5] = ["English", "Português", "Русский", "中文", "日本語"];

/// Face used for the UI text in each language (CJK needs a CJK UI font).
pub fn font_face(lang: usize) -> &'static str {
    match lang {
        3 => "Microsoft YaHei UI",
        4 => "Yu Gothic UI",
        _ => "Segoe UI",
    }
}

pub fn tr(lang: usize, key: &'static str) -> &'static str {
    let table: &[(&str, &str)] = match lang {
        1 => PT,
        2 => RU,
        3 => ZH,
        4 => JA,
        _ => return key,
    };
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v).unwrap_or(key)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn keys(t: &'static [(&'static str, &'static str)]) -> Vec<&'static str> {
        let mut k: Vec<&str> = t.iter().map(|(k, _)| *k).collect();
        k.sort();
        k
    }

    #[test]
    fn all_languages_have_the_same_keys() {
        let base = keys(PT);
        for (name, t) in [("ru", RU), ("zh", ZH), ("ja", JA)] {
            assert_eq!(base, keys(t), "language {name} has different keys than pt");
        }
    }

    #[test]
    fn no_empty_translations() {
        for (name, t) in [("pt", PT), ("ru", RU), ("zh", ZH), ("ja", JA)] {
            for (k, v) in t {
                assert!(!v.trim().is_empty(), "{name}: empty translation for {k:?}");
            }
        }
    }
}

